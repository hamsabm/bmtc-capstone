-- ============================ PART B ================================
-- Q1 INNER JOIN + GROUP BY: fleet by depot and bus type
SELECT d.DEPOT_NAME, b.BUS_TYPE, COUNT(*) AS BUSES, ROUND(AVG(b.SEATING_CAPACITY), 1) AS AVG_SEATS,
       ROUND(AVG(2026 - b.MANUFACTURE_YEAR), 1) AS AVG_AGE_YEARS
FROM BUS.BUS_MASTER b
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = b.DEPOT_ID
GROUP BY d.DEPOT_NAME, b.BUS_TYPE
ORDER BY d.DEPOT_NAME, BUSES DESC;

-- Q2 LEFT JOIN: buses that ran no trips in the period (idle assets)
SELECT b.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, d.DEPOT_NAME, COUNT(t.TRIP_ID) AS TRIPS
FROM BUS.BUS_MASTER b
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = b.DEPOT_ID
LEFT JOIN TRIP.TRIP_DATA t ON t.BUS_ID = b.BUS_ID
GROUP BY b.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, d.DEPOT_NAME
HAVING COUNT(t.TRIP_ID) = 0
ORDER BY d.DEPOT_NAME;

-- Q3 Multi-table join + CTE: route performance (trips, ridership, revenue, revenue/km)
WITH trip_stats AS (
  SELECT ROUTE_ID, COUNT(*) AS TRIPS, COUNT_IF(TRIP_STATUS = 'COMPLETED') AS COMPLETED,
         SUM(PASSENGER_COUNT) AS PASSENGERS, SUM(DISTANCE_KM) AS KM_OPERATED, AVG(DELAY_MINUTES) AS AVG_DELAY
  FROM TRIP.TRIP_DATA GROUP BY ROUTE_ID),
ticket_stats AS (
  SELECT ROUTE_ID, SUM(FARE) AS REVENUE FROM TRIP.TICKET_DATA GROUP BY ROUTE_ID)
SELECT r.ROUTE_CODE, r.ROUTE_NAME, r.ROUTE_CATEGORY, d.DEPOT_NAME, s.TRIPS, s.PASSENGERS,
       ROUND(s.PASSENGERS / NULLIF(s.COMPLETED, 0), 1) AS AVG_LOAD, k.REVENUE,
       ROUND(k.REVENUE / NULLIF(s.KM_OPERATED, 0), 2) AS REVENUE_PER_KM, ROUND(s.AVG_DELAY, 1) AS AVG_DELAY_MIN
FROM TRIP.ROUTE_MASTER r
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = r.DEPOT_ID
JOIN trip_stats s ON s.ROUTE_ID = r.ROUTE_ID
JOIN ticket_stats k ON k.ROUTE_ID = r.ROUTE_ID
ORDER BY k.REVENUE DESC;

-- Q4 Window ranking: top 3 routes by revenue within each route category
SELECT * FROM (
  SELECT r.ROUTE_CATEGORY, r.ROUTE_CODE, SUM(t.FARE) AS REVENUE,
         RANK() OVER (PARTITION BY r.ROUTE_CATEGORY ORDER BY SUM(t.FARE) DESC) AS RANK_IN_CATEGORY
  FROM TRIP.TICKET_DATA t JOIN TRIP.ROUTE_MASTER r ON r.ROUTE_ID = t.ROUTE_ID
  GROUP BY r.ROUTE_CATEGORY, r.ROUTE_CODE)
WHERE RANK_IN_CATEGORY <= 3
ORDER BY ROUTE_CATEGORY, RANK_IN_CATEGORY;

-- Q5 Top/bottom 5 routes by ridership (subquery + window)
SELECT ROUTE_CODE, PASSENGERS, POSITION FROM (
  SELECT r.ROUTE_CODE, SUM(t.PASSENGER_COUNT) AS PASSENGERS,
         ROW_NUMBER() OVER (ORDER BY SUM(t.PASSENGER_COUNT) DESC) AS RN_DESC,
         ROW_NUMBER() OVER (ORDER BY SUM(t.PASSENGER_COUNT) ASC)  AS RN_ASC,
         CASE WHEN RN_DESC <= 5 THEN 'TOP 5' ELSE 'BOTTOM 5' END AS POSITION
  FROM TRIP.TRIP_DATA t JOIN TRIP.ROUTE_MASTER r ON r.ROUTE_ID = t.ROUTE_ID
  GROUP BY r.ROUTE_CODE)
WHERE RN_DESC <= 5 OR RN_ASC <= 5
ORDER BY PASSENGERS DESC;

-- Q6 Monthly revenue trend with running total and month-over-month change (LAG)
WITH monthly AS (
  SELECT DATE_TRUNC('MONTH', TICKET_DATE) AS MONTH, COUNT(*) AS TICKETS, SUM(FARE) AS REVENUE
  FROM TRIP.TICKET_DATA GROUP BY 1)
SELECT MONTH, TICKETS, REVENUE,
       SUM(REVENUE) OVER (ORDER BY MONTH ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS RUNNING_REVENUE,
       ROUND(100 * (REVENUE - LAG(REVENUE) OVER (ORDER BY MONTH)) / NULLIF(LAG(REVENUE) OVER (ORDER BY MONTH), 0), 1) AS MOM_CHANGE_PCT
FROM monthly ORDER BY MONTH;

-- Q7 7-day moving average of daily boardings
SELECT TICKET_DATE, COUNT(*) AS BOARDINGS,
       ROUND(AVG(COUNT(*)) OVER (ORDER BY TICKET_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW), 1) AS MOVING_AVG_7D
FROM TRIP.TICKET_DATA
WHERE TICKET_DATE >= '2026-09-01'
GROUP BY TICKET_DATE ORDER BY TICKET_DATE;

-- Q8 Payment mode share (aggregate + ratio window)
SELECT PAYMENT_MODE, COUNT(*) AS TICKETS, SUM(FARE) AS REVENUE,
       ROUND(100 * RATIO_TO_REPORT(COUNT(*)) OVER (), 1) AS SHARE_PCT
FROM TRIP.TICKET_DATA GROUP BY PAYMENT_MODE ORDER BY TICKETS DESC;

-- Q9 Fuel efficiency per bus vs its bus-type average (CTE + window + CASE)
WITH bus_eff AS (
  SELECT f.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, f.UNIT,
         SUM(f.KM_SINCE_LAST_FILL) AS KM, SUM(f.QUANTITY) AS QTY, SUM(f.TOTAL_COST) AS COST,
         SUM(f.KM_SINCE_LAST_FILL) / NULLIF(SUM(f.QUANTITY), 0) AS KM_PER_UNIT
  FROM TRIP.FUEL_LOG f JOIN BUS.BUS_MASTER b ON b.BUS_ID = f.BUS_ID
  GROUP BY f.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, f.UNIT)
SELECT REGISTRATION_NO, BUS_TYPE, UNIT, ROUND(KM, 0) AS KM, ROUND(KM_PER_UNIT, 2) AS KM_PER_UNIT,
       ROUND(AVG(KM_PER_UNIT) OVER (PARTITION BY BUS_TYPE), 2) AS TYPE_AVG,
       ROUND(100 * (KM_PER_UNIT / AVG(KM_PER_UNIT) OVER (PARTITION BY BUS_TYPE) - 1), 1) AS PCT_VS_TYPE,
       CASE WHEN KM_PER_UNIT < 0.9 * AVG(KM_PER_UNIT) OVER (PARTITION BY BUS_TYPE) THEN 'INVESTIGATE'
            WHEN KM_PER_UNIT > 1.05 * AVG(KM_PER_UNIT) OVER (PARTITION BY BUS_TYPE) THEN 'EFFICIENT'
            ELSE 'NORMAL' END AS EFFICIENCY_FLAG,
       ROUND(COST / NULLIF(KM, 0), 2) AS COST_PER_KM
FROM bus_eff ORDER BY PCT_VS_TYPE;

-- Q10 Maintenance frequency and cost by depot (HAVING filters depots above fleet average cost)
SELECT d.DEPOT_NAME, COUNT(*) AS JOBS, SUM(m.TOTAL_COST) AS TOTAL_COST,
       ROUND(SUM(m.TOTAL_COST) / COUNT(DISTINCT m.BUS_ID), 0) AS COST_PER_BUS,
       SUM(m.DOWNTIME_HOURS) AS DOWNTIME_HOURS, COUNT_IF(m.SEVERITY IN ('HIGH', 'CRITICAL')) AS SERIOUS_JOBS
FROM TRIP.MAINTENANCE_LOG m
JOIN BUS.BUS_MASTER b ON b.BUS_ID = m.BUS_ID
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = b.DEPOT_ID
GROUP BY d.DEPOT_NAME
HAVING SUM(m.TOTAL_COST) / COUNT(DISTINCT m.BUS_ID) > (SELECT SUM(TOTAL_COST) / COUNT(DISTINCT BUS_ID) FROM TRIP.MAINTENANCE_LOG)
ORDER BY COST_PER_BUS DESC;

-- Q11 Correlated subquery: buses whose maintenance cost exceeds their own depot's average
WITH bus_cost AS (
  SELECT m.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, b.MANUFACTURE_YEAR, b.DEPOT_ID, SUM(m.TOTAL_COST) AS COST
  FROM TRIP.MAINTENANCE_LOG m JOIN BUS.BUS_MASTER b ON b.BUS_ID = m.BUS_ID
  GROUP BY m.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, b.MANUFACTURE_YEAR, b.DEPOT_ID)
SELECT c.REGISTRATION_NO, c.BUS_TYPE, c.MANUFACTURE_YEAR, c.DEPOT_ID, c.COST,
       (SELECT ROUND(AVG(c2.COST), 0) FROM bus_cost c2 WHERE c2.DEPOT_ID = c.DEPOT_ID) AS DEPOT_AVG_COST
FROM bus_cost c
WHERE c.COST > (SELECT AVG(c2.COST) FROM bus_cost c2 WHERE c2.DEPOT_ID = c.DEPOT_ID)
ORDER BY c.COST DESC LIMIT 15;

-- Q12 Days between successive maintenance jobs per bus (LAG over dates)
SELECT BUS_ID, MAINTENANCE_DATE, MAINTENANCE_TYPE,
       DATEDIFF(DAY, LAG(MAINTENANCE_DATE) OVER (PARTITION BY BUS_ID ORDER BY MAINTENANCE_DATE), MAINTENANCE_DATE) AS DAYS_SINCE_PREVIOUS
FROM TRIP.MAINTENANCE_LOG
QUALIFY DAYS_SINCE_PREVIOUS < 15
ORDER BY DAYS_SINCE_PREVIOUS;

-- Q13 Peak vs off-peak punctuality (CASE bucketing)
SELECT CASE WHEN HOUR(SCHEDULED_START) IN (8, 9, 17, 18, 19) THEN 'Peak' ELSE 'Off-peak' END AS PERIOD,
       COUNT(*) AS TRIPS, ROUND(AVG(DELAY_MINUTES), 1) AS AVG_DELAY,
       ROUND(100 * COUNT_IF(DELAY_MINUTES <= 5) / COUNT(*), 1) AS ON_TIME_PCT,
       ROUND(100 * COUNT_IF(TRIP_STATUS <> 'COMPLETED') / COUNT(*), 1) AS FAILED_PCT
FROM TRIP.TRIP_DATA GROUP BY PERIOD;

-- Q14 Passes: sales, revenue and usage by pass type (LEFT JOIN to aggregated validations)
SELECT p.PASS_TYPE, COUNT(*) AS PASSES_SOLD, SUM(p.PRICE) AS PASS_REVENUE,
       COUNT_IF(p.STATUS = 'ACTIVE') AS ACTIVE_PASSES, COALESCE(SUM(v.RIDES), 0) AS VALIDATIONS,
       ROUND(COALESCE(SUM(v.RIDES), 0) / COUNT(*), 1) AS AVG_RIDES_PER_PASS
FROM PASSENGER.PASS_DATA p
LEFT JOIN (SELECT PASS_ID, COUNT(*) AS RIDES FROM TRIP.TICKET_DATA WHERE PASS_ID IS NOT NULL GROUP BY PASS_ID) v
       ON v.PASS_ID = p.PASS_ID
GROUP BY p.PASS_TYPE ORDER BY PASSES_SOLD DESC;

-- Q15 Employees: driver workload ranking within depot (DENSE_RANK)
SELECT d.DEPOT_NAME, e.EMPLOYEE_CODE, e.EMPLOYEE_NAME, COUNT(*) AS TRIPS_DRIVEN, SUM(t.DISTANCE_KM) AS KM,
       DENSE_RANK() OVER (PARTITION BY d.DEPOT_NAME ORDER BY COUNT(*) DESC) AS WORKLOAD_RANK
FROM TRIP.TRIP_DATA t
JOIN BUS.EMPLOYEE_MASTER e ON e.EMPLOYEE_ID = t.DRIVER_ID
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = e.DEPOT_ID
GROUP BY d.DEPOT_NAME, e.EMPLOYEE_CODE, e.EMPLOYEE_NAME
QUALIFY WORKLOAD_RANK = 1
ORDER BY TRIPS_DRIVEN DESC;
