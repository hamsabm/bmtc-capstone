-- TCL 1 (COMMIT): buses with open workshop jobs are marked UNDER_MAINTENANCE atomically with an audit trail
BEGIN TRANSACTION;
INSERT INTO BUS.BUS_STATUS_AUDIT (BUS_ID, OLD_STATUS, NEW_STATUS, REASON)
SELECT b.BUS_ID, b.STATUS, 'UNDER_MAINTENANCE', 'Open maintenance job ' || m.MAINTENANCE_ID
