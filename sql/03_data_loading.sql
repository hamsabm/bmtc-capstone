-- =====================================================================
-- 03_data_loading.sql | Data File -> File Format -> Internal Stage -> COPY INTO
--                      -> Transient staging -> Validation -> Corrected load
-- Synthetic academic dataset produced by scripts/generate_data.py.
-- {{DATA_DIR}} is substituted by scripts/run_sql.py with the absolute data path.
-- Table types used:
--   PERMANENT  : BUS/TRIP/PASSENGER project tables (Fail-safe + Time Travel)
--   TRANSIENT  : STAGING.STG_* landing tables (re-loadable, no Fail-safe cost)
--   TEMPORARY  : STAGING.DQ_ISSUES (session-only data-quality scratch table)
-- =====================================================================
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE BMTC_WH;
USE DATABASE BMTC_DW;
USE SCHEMA STAGING;

-- ---------------------------------------------------------------- 1. File formats
CREATE OR REPLACE FILE FORMAT STAGING.FF_CSV
  TYPE = CSV
  PARSE_HEADER = TRUE                     -- read column names from the header row
  FIELD_DELIMITER = ','
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  NULL_IF = ('', 'NULL')
  TRIM_SPACE = FALSE                      -- keep whitespace so validation can detect it
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
  COMMENT = 'BMTC CSV source files with header';

CREATE OR REPLACE FILE FORMAT STAGING.FF_CSV_PREVIEW
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"' EMPTY_FIELD_AS_NULL = TRUE
  COMMENT = 'Positional CSV format for previewing staged files';

CREATE OR REPLACE FILE FORMAT STAGING.FF_JSON
  TYPE = JSON
  STRIP_OUTER_ARRAY = FALSE               -- files are newline-delimited JSON
  STRIP_NULL_VALUES = FALSE
  COMMENT = 'BMTC complaint documents (NDJSON)';

-- ---------------------------------------------------------------- 2. Internal stage + upload
CREATE OR REPLACE STAGE STAGING.BMTC_INTERNAL_STAGE
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Internal named stage for BMTC source files';

PUT 'file://{{DATA_DIR}}/*.csv' @STAGING.BMTC_INTERNAL_STAGE/csv/ AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
PUT 'file://{{DATA_DIR}}/complaints.json' @STAGING.BMTC_INTERNAL_STAGE/json/ AUTO_COMPRESS = TRUE OVERWRITE = TRUE;
LIST @STAGING.BMTC_INTERNAL_STAGE;

-- Verify Snowflake can read the staged files with the file formats
SELECT $1 AS BUS_ID, $2 AS REGISTRATION_NO, $3 AS BUS_TYPE, $4 AS DEPOT_ID
FROM @STAGING.BMTC_INTERNAL_STAGE/csv/bus_master.csv.gz (FILE_FORMAT => 'STAGING.FF_CSV_PREVIEW') LIMIT 5;
SELECT $1:complaint_id::VARCHAR AS COMPLAINT_ID, $1:category::VARCHAR AS CATEGORY, $1:service.route_code::VARCHAR AS ROUTE
FROM @STAGING.BMTC_INTERNAL_STAGE/json/complaints.json.gz (FILE_FORMAT => 'STAGING.FF_JSON') LIMIT 5;
SELECT * FROM TABLE(INFER_SCHEMA(LOCATION => '@STAGING.BMTC_INTERNAL_STAGE/csv/fuel_log.csv.gz', FILE_FORMAT => 'STAGING.FF_CSV'));

-- ---------------------------------------------------------------- 3. Transient landing tables
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_DEPOT_MASTER    LIKE BUS.DEPOT_MASTER;
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_BUS_MASTER      LIKE BUS.BUS_MASTER;
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_EMPLOYEE_MASTER LIKE BUS.EMPLOYEE_MASTER;
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_ROUTE_MASTER    LIKE TRIP.ROUTE_MASTER;
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_TRIP_DATA       LIKE TRIP.TRIP_DATA;
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_TICKET_DATA     LIKE TRIP.TICKET_DATA;
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_FUEL_LOG        LIKE TRIP.FUEL_LOG;
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_MAINTENANCE_LOG LIKE TRIP.MAINTENANCE_LOG;
CREATE OR REPLACE TRANSIENT TABLE STAGING.STG_PASS_DATA       LIKE PASSENGER.PASS_DATA;

-- ---------------------------------------------------------------- 4. COPY INTO (bad rows are skipped and reported)
COPY INTO STAGING.STG_DEPOT_MASTER    FROM @STAGING.BMTC_INTERNAL_STAGE/csv/depot_master.csv.gz    FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;
COPY INTO STAGING.STG_BUS_MASTER      FROM @STAGING.BMTC_INTERNAL_STAGE/csv/bus_master.csv.gz      FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;
COPY INTO STAGING.STG_EMPLOYEE_MASTER FROM @STAGING.BMTC_INTERNAL_STAGE/csv/employee_master.csv.gz FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;
COPY INTO STAGING.STG_ROUTE_MASTER    FROM @STAGING.BMTC_INTERNAL_STAGE/csv/route_master.csv.gz    FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;
COPY INTO STAGING.STG_TRIP_DATA       FROM @STAGING.BMTC_INTERNAL_STAGE/csv/trip_data.csv.gz       FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;
COPY INTO STAGING.STG_TICKET_DATA     FROM @STAGING.BMTC_INTERNAL_STAGE/csv/ticket_data.csv.gz     FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;
COPY INTO STAGING.STG_FUEL_LOG        FROM @STAGING.BMTC_INTERNAL_STAGE/csv/fuel_log.csv.gz        FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;
-- Persist the rejected rows of the fuel load (re-read the staged file with TRY_TO_NUMBER) for review
CREATE OR REPLACE TRANSIENT TABLE STAGING.LOAD_REJECTS AS
SELECT 'FUEL_LOG' AS SOURCE_TABLE, METADATA$FILE_ROW_NUMBER + 1 AS FILE_LINE, 'QUANTITY' AS COLUMN_NAME,
       $7 AS BAD_VALUE, 'Non-numeric QUANTITY' AS ERROR, $1 AS FUEL_ID, $2 AS BUS_ID, $4 AS FUEL_DATE
FROM @STAGING.BMTC_INTERNAL_STAGE/csv/fuel_log.csv.gz (FILE_FORMAT => 'STAGING.FF_CSV_PREVIEW')
WHERE $7 IS NOT NULL AND TRY_TO_NUMBER($7, 8, 1) IS NULL;                  
SELECT * FROM STAGING.LOAD_REJECTS;                                               
COPY INTO STAGING.STG_MAINTENANCE_LOG FROM @STAGING.BMTC_INTERNAL_STAGE/csv/maintenance_log.csv.gz FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;
COPY INTO STAGING.STG_PASS_DATA       FROM @STAGING.BMTC_INTERNAL_STAGE/csv/pass_data.csv.gz       FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_CSV') MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE ON_ERROR = CONTINUE FORCE = TRUE;

-- JSON -> VARIANT with load-time projection of key attributes
COPY INTO PASSENGER.COMPLAINTS_JSON (COMPLAINT_ID, SUBMITTED_AT, PAYLOAD, SOURCE_FILE)
FROM (SELECT $1:complaint_id::VARCHAR, $1:submitted_at::TIMESTAMP_NTZ, $1, METADATA$FILENAME
      FROM @STAGING.BMTC_INTERNAL_STAGE/json/complaints.json.gz)
FILE_FORMAT = (FORMAT_NAME = 'STAGING.FF_JSON') ON_ERROR = ABORT_STATEMENT FORCE = TRUE;

-- Load audit: files, rows parsed, rows loaded, first error (rejected 'twelve' quantity row)
SELECT TABLE_NAME, FILE_NAME, ROW_PARSED, ROW_COUNT AS ROWS_LOADED, ERROR_COUNT, FIRST_ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'STAGING.STG_FUEL_LOG', START_TIME => DATEADD(HOUR, -1, CURRENT_TIMESTAMP())))
ORDER BY LAST_LOAD_TIME DESC LIMIT 1;


-- ---------------------------------------------------------------- 5. Data-quality detection (TEMPORARY table)
CREATE OR REPLACE TEMPORARY TABLE STAGING.DQ_ISSUES (
  PHASE VARCHAR, TABLE_NAME VARCHAR, CHECK_NAME VARCHAR, ISSUE_COUNT NUMBER);

INSERT INTO STAGING.DQ_ISSUES
SELECT 'BEFORE', 'TRIP_DATA', 'Duplicate TRIP_ID rows', COUNT(*) - COUNT(DISTINCT TRIP_ID) FROM STAGING.STG_TRIP_DATA
UNION ALL SELECT 'BEFORE', 'TRIP_DATA', 'Negative PASSENGER_COUNT', COUNT_IF(PASSENGER_COUNT < 0) FROM STAGING.STG_TRIP_DATA
UNION ALL SELECT 'BEFORE', 'TICKET_DATA', 'Duplicate TICKET_ID rows', COUNT(*) - COUNT(DISTINCT TICKET_ID) FROM STAGING.STG_TICKET_DATA
UNION ALL SELECT 'BEFORE', 'TICKET_DATA', 'Orphan tickets (TRIP_ID not in trips)', COUNT(*) FROM STAGING.STG_TICKET_DATA t
          WHERE NOT EXISTS (SELECT 1 FROM STAGING.STG_TRIP_DATA x WHERE x.TRIP_ID = t.TRIP_ID)
UNION ALL SELECT 'BEFORE', 'PASS_DATA', 'Non-standard STATUS (case/whitespace)', COUNT_IF(STATUS <> UPPER(TRIM(STATUS))) FROM STAGING.STG_PASS_DATA
UNION ALL SELECT 'BEFORE', 'PASS_DATA', 'Missing VALID_TO', COUNT_IF(VALID_TO IS NULL) FROM STAGING.STG_PASS_DATA
UNION ALL SELECT 'BEFORE', 'PASS_DATA', 'Missing EMAIL (optional, reported only)', COUNT_IF(EMAIL IS NULL) FROM STAGING.STG_PASS_DATA
UNION ALL SELECT 'BEFORE', 'FUEL_LOG', 'Missing QUANTITY', COUNT_IF(QUANTITY IS NULL) FROM STAGING.STG_FUEL_LOG
UNION ALL SELECT 'BEFORE', 'FUEL_LOG', 'Rows rejected by COPY (invalid data type)',
          (SELECT ERROR_COUNT FROM TABLE(INFORMATION_SCHEMA.COPY_HISTORY(TABLE_NAME => 'STAGING.STG_FUEL_LOG',
                  START_TIME => DATEADD(HOUR, -1, CURRENT_TIMESTAMP()))) ORDER BY LAST_LOAD_TIME DESC LIMIT 1)
UNION ALL SELECT 'BEFORE', 'MAINTENANCE_LOG', 'Negative PARTS_COST', COUNT_IF(PARTS_COST < 0) FROM STAGING.STG_MAINTENANCE_LOG
UNION ALL SELECT 'BEFORE', 'BUS_MASTER', 'Bus with unknown DEPOT_ID', COUNT(*) FROM STAGING.STG_BUS_MASTER b
          WHERE b.DEPOT_ID NOT IN (SELECT DEPOT_ID FROM STAGING.STG_DEPOT_MASTER);

SELECT * FROM STAGING.DQ_ISSUES ORDER BY TABLE_NAME, CHECK_NAME;

-- ---------------------------------------------------------------- 6. Corrected load into permanent tables
INSERT INTO BUS.DEPOT_MASTER SELECT * FROM STAGING.STG_DEPOT_MASTER QUALIFY ROW_NUMBER() OVER (PARTITION BY DEPOT_ID ORDER BY DEPOT_ID) = 1;

INSERT INTO BUS.BUS_MASTER (BUS_ID, REGISTRATION_NO, BUS_TYPE, DEPOT_ID, MANUFACTURER, MANUFACTURE_YEAR,
                            SEATING_CAPACITY, FUEL_TYPE, STATUS, COMMISSION_DATE)
SELECT BUS_ID, REGISTRATION_NO, BUS_TYPE, DEPOT_ID, MANUFACTURER, MANUFACTURE_YEAR, SEATING_CAPACITY,
       FUEL_TYPE, UPPER(TRIM(STATUS)), COMMISSION_DATE
FROM STAGING.STG_BUS_MASTER QUALIFY ROW_NUMBER() OVER (PARTITION BY BUS_ID ORDER BY BUS_ID) = 1;

INSERT INTO BUS.EMPLOYEE_MASTER SELECT * FROM STAGING.STG_EMPLOYEE_MASTER
QUALIFY ROW_NUMBER() OVER (PARTITION BY EMPLOYEE_ID ORDER BY EMPLOYEE_ID) = 1;

INSERT INTO TRIP.ROUTE_MASTER SELECT * FROM STAGING.STG_ROUTE_MASTER
QUALIFY ROW_NUMBER() OVER (PARTITION BY ROUTE_ID ORDER BY ROUTE_ID) = 1;

-- Fix: remove exact duplicates, correct sign errors in PASSENGER_COUNT
INSERT INTO TRIP.TRIP_DATA
SELECT TRIP_ID, BUS_ID, ROUTE_ID, DRIVER_ID, CONDUCTOR_ID, TRIP_DATE, SCHEDULED_START, ACTUAL_START, ACTUAL_END,
       DELAY_MINUTES, ABS(PASSENGER_COUNT), DISTANCE_KM, UPPER(TRIM(TRIP_STATUS))
FROM STAGING.STG_TRIP_DATA QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIP_ID ORDER BY TRIP_ID) = 1;

-- Fix: remove duplicates and orphan tickets
INSERT INTO TRIP.TICKET_DATA
SELECT t.* FROM STAGING.STG_TICKET_DATA t
WHERE EXISTS (SELECT 1 FROM TRIP.TRIP_DATA x WHERE x.TRIP_ID = t.TRIP_ID)
QUALIFY ROW_NUMBER() OVER (PARTITION BY t.TICKET_ID ORDER BY t.TICKET_ID) = 1;

-- Fix: impute missing QUANTITY from TOTAL_COST / UNIT_PRICE
INSERT INTO TRIP.FUEL_LOG
SELECT FUEL_ID, BUS_ID, DEPOT_ID, FUEL_DATE, FUEL_TYPE, UNIT,
       COALESCE(QUANTITY, ROUND(TOTAL_COST / NULLIF(UNIT_PRICE, 0), 1)), UNIT_PRICE, TOTAL_COST,
       ODOMETER_KM, KM_SINCE_LAST_FILL, STATION
FROM STAGING.STG_FUEL_LOG QUALIFY ROW_NUMBER() OVER (PARTITION BY FUEL_ID ORDER BY FUEL_ID) = 1;

-- Fix: negative parts cost (sign error)
INSERT INTO TRIP.MAINTENANCE_LOG
SELECT MAINTENANCE_ID, BUS_ID, MAINTENANCE_DATE, MAINTENANCE_TYPE, DESCRIPTION, ABS(PARTS_COST), LABOUR_COST,
       ABS(PARTS_COST) + LABOUR_COST, DOWNTIME_HOURS, SEVERITY, MECHANIC_ID, STATUS
FROM STAGING.STG_MAINTENANCE_LOG QUALIFY ROW_NUMBER() OVER (PARTITION BY MAINTENANCE_ID ORDER BY MAINTENANCE_ID) = 1;

-- Fix: standardise STATUS, derive missing VALID_TO from the pass validity rule
INSERT INTO PASSENGER.PASS_DATA
SELECT PASS_ID, PASS_NUMBER, PASSENGER_NAME, PHONE, EMAIL, PASS_TYPE, PASSENGER_CATEGORY, ISSUE_DATE, VALID_FROM,
       COALESCE(VALID_TO, DATEADD(DAY, CASE PASS_TYPE WHEN 'Daily Pass' THEN 0
                                                     WHEN 'Monthly General' THEN 29
                                                     WHEN 'Monthly Vajra' THEN 29
                                                     WHEN 'Student Pass' THEN 179
                                                     WHEN 'Senior Citizen Pass' THEN 364 END, VALID_FROM)),
       PRICE, ISSUING_DEPOT_ID, UPPER(TRIM(STATUS))
FROM STAGING.STG_PASS_DATA QUALIFY ROW_NUMBER() OVER (PARTITION BY PASS_ID ORDER BY PASS_ID) = 1;

-- ---------------------------------------------------------------- 7. Post-load validation
INSERT INTO STAGING.DQ_ISSUES
SELECT 'AFTER', 'TRIP_DATA', 'Duplicate TRIP_ID rows', COUNT(*) - COUNT(DISTINCT TRIP_ID) FROM TRIP.TRIP_DATA
UNION ALL SELECT 'AFTER', 'TRIP_DATA', 'Negative PASSENGER_COUNT', COUNT_IF(PASSENGER_COUNT < 0) FROM TRIP.TRIP_DATA
UNION ALL SELECT 'AFTER', 'TICKET_DATA', 'Duplicate TICKET_ID rows', COUNT(*) - COUNT(DISTINCT TICKET_ID) FROM TRIP.TICKET_DATA
UNION ALL SELECT 'AFTER', 'TICKET_DATA', 'Orphan tickets (TRIP_ID not in trips)', COUNT(*) FROM TRIP.TICKET_DATA t
          WHERE NOT EXISTS (SELECT 1 FROM TRIP.TRIP_DATA x WHERE x.TRIP_ID = t.TRIP_ID)
UNION ALL SELECT 'AFTER', 'PASS_DATA', 'Non-standard STATUS (case/whitespace)', COUNT_IF(STATUS <> UPPER(TRIM(STATUS))) FROM PASSENGER.PASS_DATA
UNION ALL SELECT 'AFTER', 'PASS_DATA', 'Missing VALID_TO', COUNT_IF(VALID_TO IS NULL) FROM PASSENGER.PASS_DATA
UNION ALL SELECT 'AFTER', 'PASS_DATA', 'Missing EMAIL (optional, reported only)', COUNT_IF(EMAIL IS NULL) FROM PASSENGER.PASS_DATA
UNION ALL SELECT 'AFTER', 'FUEL_LOG', 'Missing QUANTITY', COUNT_IF(QUANTITY IS NULL) FROM TRIP.FUEL_LOG
UNION ALL SELECT 'AFTER', 'MAINTENANCE_LOG', 'Negative PARTS_COST', COUNT_IF(PARTS_COST < 0) FROM TRIP.MAINTENANCE_LOG
UNION ALL SELECT 'AFTER', 'TRIP_DATA', 'PASSENGER_COUNT <> tickets issued', COUNT(*) FROM TRIP.TRIP_DATA t
          LEFT JOIN (SELECT TRIP_ID, COUNT(*) N FROM TRIP.TICKET_DATA GROUP BY TRIP_ID) k ON k.TRIP_ID = t.TRIP_ID
          WHERE t.PASSENGER_COUNT <> COALESCE(k.N, 0)
UNION ALL SELECT 'AFTER', 'TRIP_DATA', 'Trips with unknown BUS/ROUTE', COUNT(*) FROM TRIP.TRIP_DATA t
          WHERE t.BUS_ID NOT IN (SELECT BUS_ID FROM BUS.BUS_MASTER) OR t.ROUTE_ID NOT IN (SELECT ROUTE_ID FROM TRIP.ROUTE_MASTER)
UNION ALL SELECT 'AFTER', 'COMPLAINTS_JSON', 'Complaints referencing unknown trip', COUNT(*) FROM PASSENGER.COMPLAINTS_JSON c
          WHERE c.PAYLOAD:service.trip_id::NUMBER NOT IN (SELECT TRIP_ID FROM TRIP.TRIP_DATA);

-- Before vs after comparison of every check
SELECT TABLE_NAME, CHECK_NAME,
       MAX(IFF(PHASE = 'BEFORE', ISSUE_COUNT, NULL)) AS BEFORE_FIX,
       MAX(IFF(PHASE = 'AFTER',  ISSUE_COUNT, NULL)) AS AFTER_FIX
FROM STAGING.DQ_ISSUES GROUP BY TABLE_NAME, CHECK_NAME ORDER BY TABLE_NAME, CHECK_NAME;

-- Staged vs loaded row counts
SELECT 'DEPOT_MASTER' AS TABLE_NAME, (SELECT COUNT(*) FROM STAGING.STG_DEPOT_MASTER) AS STAGED, (SELECT COUNT(*) FROM BUS.DEPOT_MASTER) AS LOADED
UNION ALL SELECT 'BUS_MASTER',      (SELECT COUNT(*) FROM STAGING.STG_BUS_MASTER),      (SELECT COUNT(*) FROM BUS.BUS_MASTER)
UNION ALL SELECT 'EMPLOYEE_MASTER', (SELECT COUNT(*) FROM STAGING.STG_EMPLOYEE_MASTER), (SELECT COUNT(*) FROM BUS.EMPLOYEE_MASTER)
UNION ALL SELECT 'ROUTE_MASTER',    (SELECT COUNT(*) FROM STAGING.STG_ROUTE_MASTER),    (SELECT COUNT(*) FROM TRIP.ROUTE_MASTER)
UNION ALL SELECT 'TRIP_DATA',       (SELECT COUNT(*) FROM STAGING.STG_TRIP_DATA),       (SELECT COUNT(*) FROM TRIP.TRIP_DATA)
UNION ALL SELECT 'TICKET_DATA',     (SELECT COUNT(*) FROM STAGING.STG_TICKET_DATA),     (SELECT COUNT(*) FROM TRIP.TICKET_DATA)
UNION ALL SELECT 'FUEL_LOG',        (SELECT COUNT(*) FROM STAGING.STG_FUEL_LOG),        (SELECT COUNT(*) FROM TRIP.FUEL_LOG)
UNION ALL SELECT 'MAINTENANCE_LOG', (SELECT COUNT(*) FROM STAGING.STG_MAINTENANCE_LOG), (SELECT COUNT(*) FROM TRIP.MAINTENANCE_LOG)
UNION ALL SELECT 'PASS_DATA',       (SELECT COUNT(*) FROM STAGING.STG_PASS_DATA),       (SELECT COUNT(*) FROM PASSENGER.PASS_DATA)
UNION ALL SELECT 'COMPLAINTS_JSON', NULL,                                               (SELECT COUNT(*) FROM PASSENGER.COMPLAINTS_JSON);

-- Mandatory-column NULL check on loaded data (must be all zero)
SELECT COUNT_IF(BUS_ID IS NULL OR ROUTE_ID IS NULL OR TRIP_DATE IS NULL) AS TRIP_KEY_NULLS,
       (SELECT COUNT_IF(FARE IS NULL OR TRIP_ID IS NULL) FROM TRIP.TICKET_DATA) AS TICKET_KEY_NULLS,
       (SELECT COUNT_IF(PAYLOAD IS NULL OR COMPLAINT_ID IS NULL) FROM PASSENGER.COMPLAINTS_JSON) AS COMPLAINT_NULLS
FROM TRIP.TRIP_DATA;
