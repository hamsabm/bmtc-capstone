-- Single-row KPI view for dashboard cards
CREATE OR REPLACE VIEW TRIP.V_DASHBOARD_KPIS
COMMENT = 'Headline KPIs for the dashboard (Streamlit Dashboard page, Power BI cards)' AS
SELECT
  (SELECT COUNT(*) FROM BUS.BUS_MASTER)                                   AS TOTAL_BUSES,
  (SELECT COUNT_IF(STATUS = 'ACTIVE') FROM BUS.BUS_MASTER)                AS ACTIVE_BUSES,
  (SELECT COUNT(*) FROM BUS.DEPOT_MASTER)                                 AS TOTAL_DEPOTS,
  (SELECT COUNT(*) FROM BUS.EMPLOYEE_MASTER)                              AS TOTAL_EMPLOYEES,
  (SELECT COUNT(*) FROM TRIP.ROUTE_MASTER)                                AS TOTAL_ROUTES,
  (SELECT COUNT(*) FROM TRIP.TRIP_DATA)                                   AS TOTAL_TRIPS,
  (SELECT COUNT(*) FROM TRIP.TICKET_DATA)                                 AS TOTAL_TICKETS,
  (SELECT SUM(FARE) FROM TRIP.TICKET_DATA)                                AS TICKET_REVENUE,
  (SELECT COUNT(*) FROM PASSENGER.PASS_DATA)                              AS TOTAL_PASSES,
  (SELECT COUNT_IF(STATUS = 'ACTIVE') FROM PASSENGER.PASS_DATA)           AS ACTIVE_PASSES,
  (SELECT COUNT(*) FROM PASSENGER.COMPLAINTS_JSON)                        AS TOTAL_COMPLAINTS,
  (SELECT COUNT_IF(PAYLOAD:resolution.status::VARCHAR IN ('Open', 'In Progress')) FROM PASSENGER.COMPLAINTS_JSON) AS OPEN_COMPLAINTS,
  (SELECT COUNT(*) FROM TRIP.FUEL_LOG)                                    AS TOTAL_FUEL_RECORDS,
  (SELECT SUM(TOTAL_COST) FROM TRIP.FUEL_LOG)                             AS FUEL_COST,
  (SELECT COUNT(*) FROM TRIP.MAINTENANCE_LOG)                             AS TOTAL_MAINTENANCE_RECORDS,
  (SELECT SUM(TOTAL_COST) FROM TRIP.MAINTENANCE_LOG)                      AS MAINTENANCE_COST,
  (SELECT ROUND(100 * COUNT_IF(DELAY_MINUTES <= 5) / NULLIF(COUNT(DELAY_MINUTES), 0), 1) FROM TRIP.TRIP_DATA) AS ON_TIME_PCT;

-- Trip-level fact view (joins 4 tables + ticket aggregates)
CREATE OR REPLACE VIEW TRIP.V_TRIP_DETAILS
COMMENT = 'One row per trip enriched with route, bus, depot and ticket revenue' AS
SELECT t.TRIP_ID, t.TRIP_DATE, DATE_TRUNC('MONTH', t.TRIP_DATE) AS TRIP_MONTH, DAYNAME(t.TRIP_DATE) AS WEEKDAY,
       HOUR(t.SCHEDULED_START) AS START_HOUR,
       IFF(HOUR(t.SCHEDULED_START) IN (8, 9, 17, 18, 19), 'Peak', 'Off-peak') AS PERIOD,
       t.ROUTE_ID, r.ROUTE_CODE, r.ROUTE_NAME, r.ROUTE_CATEGORY,
       t.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, b.DEPOT_ID, d.DEPOT_NAME,
       t.TRIP_STATUS, t.DELAY_MINUTES, t.PASSENGER_COUNT, t.DISTANCE_KM,
       ROUND(t.PASSENGER_COUNT / NULLIF(b.SEATING_CAPACITY, 0), 2) AS OCCUPANCY_RATIO,
       COALESCE(k.TICKETS, 0) AS TICKETS, COALESCE(k.REVENUE, 0) AS REVENUE
FROM TRIP.TRIP_DATA t
JOIN TRIP.ROUTE_MASTER r ON r.ROUTE_ID = t.ROUTE_ID
JOIN BUS.BUS_MASTER b ON b.BUS_ID = t.BUS_ID
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = b.DEPOT_ID
LEFT JOIN (SELECT TRIP_ID, COUNT(*) AS TICKETS, SUM(FARE) AS REVENUE FROM TRIP.TICKET_DATA GROUP BY TRIP_ID) k
       ON k.TRIP_ID = t.TRIP_ID;

-- Route analytics
CREATE OR REPLACE VIEW TRIP.V_ROUTE_PERFORMANCE
COMMENT = 'Route KPIs: trips, ridership, revenue, punctuality, ranking' AS
SELECT r.ROUTE_ID, r.ROUTE_CODE, r.ROUTE_NAME, r.ROUTE_CATEGORY, r.DISTANCE_KM, r.ACTIVE_FLAG, d.DEPOT_NAME,
       COUNT(t.TRIP_ID) AS TRIPS,
       COUNT_IF(t.TRIP_STATUS = 'COMPLETED') AS COMPLETED_TRIPS,
       COUNT_IF(t.TRIP_STATUS = 'CANCELLED') AS CANCELLED_TRIPS,
       COALESCE(SUM(t.PASSENGER_COUNT), 0) AS PASSENGERS,
       COALESCE(SUM(t.REVENUE), 0) AS REVENUE,
       ROUND(SUM(t.REVENUE) / NULLIF(SUM(t.DISTANCE_KM), 0), 2) AS REVENUE_PER_KM,
       ROUND(AVG(t.DELAY_MINUTES), 1) AS AVG_DELAY_MIN,
       ROUND(AVG(t.OCCUPANCY_RATIO), 2) AS AVG_OCCUPANCY,
       RANK() OVER (ORDER BY COALESCE(SUM(t.REVENUE), 0) DESC) AS REVENUE_RANK
FROM TRIP.ROUTE_MASTER r
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = r.DEPOT_ID
LEFT JOIN TRIP.V_TRIP_DETAILS t ON t.ROUTE_ID = r.ROUTE_ID
GROUP BY r.ROUTE_ID, r.ROUTE_CODE, r.ROUTE_NAME, r.ROUTE_CATEGORY, r.DISTANCE_KM, r.ACTIVE_FLAG, d.DEPOT_NAME;

-- Daily time series for trend charts
CREATE OR REPLACE VIEW TRIP.V_DAILY_OPERATIONS
COMMENT = 'Daily trips, ridership, revenue and punctuality' AS
SELECT TRIP_DATE, COUNT(*) AS TRIPS, SUM(PASSENGER_COUNT) AS PASSENGERS, SUM(REVENUE) AS REVENUE,
       ROUND(AVG(DELAY_MINUTES), 1) AS AVG_DELAY_MIN, COUNT_IF(TRIP_STATUS <> 'COMPLETED') AS FAILED_TRIPS
FROM TRIP.V_TRIP_DETAILS GROUP BY TRIP_DATE;

-- Fuel analytics
CREATE OR REPLACE VIEW TRIP.V_FUEL_EFFICIENCY
COMMENT = 'Fuel/charging events with efficiency (km per litre or km per kWh) and cost per km' AS
SELECT f.FUEL_ID, f.FUEL_DATE, DATE_TRUNC('MONTH', f.FUEL_DATE) AS FUEL_MONTH, f.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE,
       b.MANUFACTURE_YEAR, d.DEPOT_NAME, f.FUEL_TYPE, f.UNIT, f.QUANTITY, f.UNIT_PRICE, f.TOTAL_COST,
       f.KM_SINCE_LAST_FILL, f.ODOMETER_KM,
       ROUND(f.KM_SINCE_LAST_FILL / NULLIF(f.QUANTITY, 0), 2) AS KM_PER_UNIT,
       ROUND(f.TOTAL_COST / NULLIF(f.KM_SINCE_LAST_FILL, 0), 2) AS COST_PER_KM
FROM TRIP.FUEL_LOG f
JOIN BUS.BUS_MASTER b ON b.BUS_ID = f.BUS_ID
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = b.DEPOT_ID;

-- Maintenance analytics
CREATE OR REPLACE VIEW TRIP.V_MAINTENANCE_DETAILS
COMMENT = 'Maintenance jobs with bus, depot and mechanic' AS
SELECT m.MAINTENANCE_ID, m.MAINTENANCE_DATE, DATE_TRUNC('MONTH', m.MAINTENANCE_DATE) AS MAINTENANCE_MONTH,
       m.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, b.MANUFACTURE_YEAR, d.DEPOT_NAME, m.MAINTENANCE_TYPE, m.DESCRIPTION,
       m.PARTS_COST, m.LABOUR_COST, m.TOTAL_COST, m.DOWNTIME_HOURS, m.SEVERITY, m.STATUS,
       e.EMPLOYEE_NAME AS MECHANIC_NAME
FROM TRIP.MAINTENANCE_LOG m
JOIN BUS.BUS_MASTER b ON b.BUS_ID = m.BUS_ID
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = b.DEPOT_ID
LEFT JOIN BUS.EMPLOYEE_MASTER e ON e.EMPLOYEE_ID = m.MECHANIC_ID;

-- Bus-level fuel + maintenance + utilisation summary
CREATE OR REPLACE VIEW BUS.V_BUS_SUMMARY
COMMENT = 'Per-bus utilisation, fuel efficiency and maintenance burden' AS
SELECT b.BUS_ID, b.REGISTRATION_NO, b.BUS_TYPE, b.FUEL_TYPE, b.MANUFACTURER, b.MANUFACTURE_YEAR, b.STATUS,
       d.DEPOT_NAME, d.ZONE,
       COALESCE(t.TRIPS, 0) AS TRIPS, COALESCE(t.KM, 0) AS KM_OPERATED, COALESCE(t.PASSENGERS, 0) AS PASSENGERS,
       f.FUEL_QTY, f.FUEL_COST, ROUND(f.FUEL_KM / NULLIF(f.FUEL_QTY, 0), 2) AS KM_PER_UNIT,
       COALESCE(m.JOBS, 0) AS MAINTENANCE_JOBS, COALESCE(m.COST, 0) AS MAINTENANCE_COST,
       COALESCE(m.DOWNTIME, 0) AS DOWNTIME_HOURS, m.LAST_SERVICE
FROM BUS.BUS_MASTER b
JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = b.DEPOT_ID
LEFT JOIN (SELECT BUS_ID, COUNT(*) TRIPS, SUM(DISTANCE_KM) KM, SUM(PASSENGER_COUNT) PASSENGERS
           FROM TRIP.TRIP_DATA GROUP BY BUS_ID) t ON t.BUS_ID = b.BUS_ID
LEFT JOIN (SELECT BUS_ID, SUM(QUANTITY) FUEL_QTY, SUM(TOTAL_COST) FUEL_COST, SUM(KM_SINCE_LAST_FILL) FUEL_KM
           FROM TRIP.FUEL_LOG GROUP BY BUS_ID) f ON f.BUS_ID = b.BUS_ID
LEFT JOIN (SELECT BUS_ID, COUNT(*) JOBS, SUM(TOTAL_COST) COST, SUM(DOWNTIME_HOURS) DOWNTIME, MAX(MAINTENANCE_DATE) LAST_SERVICE
           FROM TRIP.MAINTENANCE_LOG GROUP BY BUS_ID) m ON m.BUS_ID = b.BUS_ID;

-- Complaint analytics: JSON flattened into columns
CREATE OR REPLACE VIEW PASSENGER.V_COMPLAINT_ANALYTICS
COMMENT = 'Complaint JSON documents projected into relational columns' AS
SELECT c.COMPLAINT_ID, c.SUBMITTED_AT, DATE_TRUNC('MONTH', c.SUBMITTED_AT)::DATE AS COMPLAINT_MONTH,
       c.PAYLOAD:category::VARCHAR AS CATEGORY, c.PAYLOAD:sub_category::VARCHAR AS SUB_CATEGORY,
       c.PAYLOAD:priority::VARCHAR AS PRIORITY, c.PAYLOAD:channel::VARCHAR AS CHANNEL,
       c.PAYLOAD:description::VARCHAR AS DESCRIPTION,
       c.PAYLOAD:service.trip_id::NUMBER AS TRIP_ID, c.PAYLOAD:service.route_id::NUMBER AS ROUTE_ID,
       c.PAYLOAD:service.route_code::VARCHAR AS ROUTE_CODE, c.PAYLOAD:service.bus_id::NUMBER AS BUS_ID,
       d.DEPOT_NAME, c.PAYLOAD:location.stop_name::VARCHAR AS STOP_NAME,
       c.PAYLOAD:location.geo.lat::FLOAT AS LAT, c.PAYLOAD:location.geo.lon::FLOAT AS LON,
       c.PAYLOAD:passenger.is_registered::BOOLEAN AS IS_REGISTERED, c.PAYLOAD:passenger.language::VARCHAR AS LANGUAGE,
       c.PAYLOAD:resolution.status::VARCHAR AS RESOLUTION_STATUS,
       c.PAYLOAD:resolution.resolution_days::NUMBER AS RESOLUTION_DAYS,
       c.PAYLOAD:resolution.satisfaction_rating::NUMBER AS SATISFACTION_RATING,
       ARRAY_TO_STRING(c.PAYLOAD:tags, ', ') AS TAGS,
       IFF(c.SOURCE_FILE LIKE 'feed/%', 'Snowpipe feed', IFF(c.SOURCE_FILE = 'APP', 'Application', 'Bulk load')) AS INGESTION
FROM PASSENGER.COMPLAINTS_JSON c
LEFT JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = c.PAYLOAD:service.depot_id::NUMBER;

-- Pass analytics (no personal data)
CREATE OR REPLACE VIEW PASSENGER.V_PASS_SUMMARY
COMMENT = 'Monthly pass sales by type (no personal data)' AS
SELECT DATE_TRUNC('MONTH', ISSUE_DATE) AS ISSUE_MONTH, PASS_TYPE, PASSENGER_CATEGORY,
       COUNT(*) AS PASSES_ISSUED, SUM(PRICE) AS PASS_REVENUE, COUNT_IF(STATUS = 'ACTIVE') AS ACTIVE_PASSES
FROM PASSENGER.PASS_DATA GROUP BY 1, 2, 3;

-- Materialized view: pre-aggregated daily route revenue (single-table aggregate, as MV rules require)
CREATE OR REPLACE MATERIALIZED VIEW TRIP.MV_DAILY_ROUTE_REVENUE
COMMENT = 'Materialized daily ticket revenue per route (Enterprise feature)' AS
SELECT TICKET_DATE, ROUTE_ID, COUNT(*) AS TICKETS, SUM(FARE) AS REVENUE, COUNT(PASS_ID) AS PASS_VALIDATIONS
FROM TRIP.TICKET_DATA
GROUP BY TICKET_DATE, ROUTE_ID;                                                      -- @optional

SHOW MATERIALIZED VIEWS IN SCHEMA TRIP;                                              -- @optional
SELECT TICKET_DATE, SUM(REVENUE) AS REVENUE FROM TRIP.MV_DAILY_ROUTE_REVENUE
WHERE TICKET_DATE >= '2026-10-25' GROUP BY TICKET_DATE ORDER BY TICKET_DATE;         -- @optional

