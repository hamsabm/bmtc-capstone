-- =====================================================================
-- 08_streams_tasks.sql | Data Change -> Stream -> Task -> Target table
-- TRIP.TRIP_DATA changes are captured by TRIP.TRIP_DATA_STREAM. The task
-- TRIP.TASK_REFRESH_TRIP_SUMMARY calls TRIP.SP_APPLY_TRIP_CHANGES(), which
-- applies the net delta (inserts +, deletes -, updates = delete+insert)
-- to the route x day summary TRIP.TRIP_ANALYTICS_SUMMARY and logs the run.
-- The task runs hourly but only when the stream has data (WHEN clause),
-- so an idle stream costs no warehouse credits.
-- =====================================================================
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE BMTC_WH;
USE DATABASE BMTC_DW;

ALTER TASK IF EXISTS TRIP.TASK_REFRESH_TRIP_SUMMARY SUSPEND;

CREATE OR REPLACE TABLE TRIP.TRIP_ANALYTICS_SUMMARY (
  ROUTE_ID         NUMBER(5)  NOT NULL,
  TRIP_DATE        DATE       NOT NULL,
  TRIPS            NUMBER     NOT NULL,
  COMPLETED_TRIPS  NUMBER,
  CANCELLED_TRIPS  NUMBER,
  BREAKDOWN_TRIPS  NUMBER,
  PASSENGERS       NUMBER,
  DISTANCE_KM      NUMBER(12,1),
  TOTAL_DELAY_MIN  NUMBER,
  LAST_UPDATED     TIMESTAMP_NTZ,
  PRIMARY KEY (ROUTE_ID, TRIP_DATE)
) COMMENT = 'Route x day operational summary maintained incrementally by a task';

CREATE OR REPLACE TABLE TRIP.TASK_RUN_LOG (
  RUN_AT        TIMESTAMP_NTZ,
  CHANGE_ROWS   NUMBER,
  INSERTS       NUMBER,
  DELETES       NUMBER,
  MESSAGE       VARCHAR
);

-- Initial backfill from the full table
INSERT INTO TRIP.TRIP_ANALYTICS_SUMMARY
SELECT ROUTE_ID, TRIP_DATE, COUNT(*), COUNT_IF(TRIP_STATUS = 'COMPLETED'), COUNT_IF(TRIP_STATUS = 'CANCELLED'),
       COUNT_IF(TRIP_STATUS = 'BREAKDOWN'), SUM(COALESCE(PASSENGER_COUNT, 0)), SUM(COALESCE(DISTANCE_KM, 0)),
       SUM(COALESCE(DELAY_MINUTES, 0)), CURRENT_TIMESTAMP()
FROM TRIP.TRIP_DATA GROUP BY ROUTE_ID, TRIP_DATE;

-- Stream created after the backfill: it captures every change from now on
CREATE OR REPLACE STREAM TRIP.TRIP_DATA_STREAM ON TABLE TRIP.TRIP_DATA
  COMMENT = 'CDC on trip operations for the summary task';

CREATE OR REPLACE PROCEDURE TRIP.SP_APPLY_TRIP_CHANGES()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  n_rows INTEGER DEFAULT 0;
  n_ins  INTEGER DEFAULT 0;
  n_del  INTEGER DEFAULT 0;
BEGIN
  BEGIN TRANSACTION;   -- stream offset advances only at COMMIT, so all reads see the same delta
  SELECT COUNT(*), COUNT_IF(METADATA$ACTION = 'INSERT'), COUNT_IF(METADATA$ACTION = 'DELETE')
    INTO :n_rows, :n_ins, :n_del FROM TRIP.TRIP_DATA_STREAM;

  MERGE INTO TRIP.TRIP_ANALYTICS_SUMMARY tgt
  USING (
    SELECT ROUTE_ID, TRIP_DATE,
           SUM(s)                                              AS D_TRIPS,
           SUM(s * IFF(TRIP_STATUS = 'COMPLETED', 1, 0))      AS D_COMPLETED,
           SUM(s * IFF(TRIP_STATUS = 'CANCELLED', 1, 0))      AS D_CANCELLED,
           SUM(s * IFF(TRIP_STATUS = 'BREAKDOWN', 1, 0))      AS D_BREAKDOWN,
           SUM(s * COALESCE(PASSENGER_COUNT, 0))              AS D_PAX,
           SUM(s * COALESCE(DISTANCE_KM, 0))                  AS D_KM,
           SUM(s * COALESCE(DELAY_MINUTES, 0))                AS D_DELAY
    FROM (SELECT *, IFF(METADATA$ACTION = 'INSERT', 1, -1) AS s FROM TRIP.TRIP_DATA_STREAM)
    GROUP BY ROUTE_ID, TRIP_DATE
  ) src
  ON tgt.ROUTE_ID = src.ROUTE_ID AND tgt.TRIP_DATE = src.TRIP_DATE
  WHEN MATCHED THEN UPDATE SET
    TRIPS = tgt.TRIPS + src.D_TRIPS, COMPLETED_TRIPS = tgt.COMPLETED_TRIPS + src.D_COMPLETED,
    CANCELLED_TRIPS = tgt.CANCELLED_TRIPS + src.D_CANCELLED, BREAKDOWN_TRIPS = tgt.BREAKDOWN_TRIPS + src.D_BREAKDOWN,
    PASSENGERS = tgt.PASSENGERS + src.D_PAX, DISTANCE_KM = tgt.DISTANCE_KM + src.D_KM,
    TOTAL_DELAY_MIN = tgt.TOTAL_DELAY_MIN + src.D_DELAY, LAST_UPDATED = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED AND src.D_TRIPS > 0 THEN INSERT
    (ROUTE_ID, TRIP_DATE, TRIPS, COMPLETED_TRIPS, CANCELLED_TRIPS, BREAKDOWN_TRIPS, PASSENGERS, DISTANCE_KM, TOTAL_DELAY_MIN, LAST_UPDATED)
    VALUES (src.ROUTE_ID, src.TRIP_DATE, src.D_TRIPS, src.D_COMPLETED, src.D_CANCELLED, src.D_BREAKDOWN,
            src.D_PAX, src.D_KM, src.D_DELAY, CURRENT_TIMESTAMP());

  DELETE FROM TRIP.TRIP_ANALYTICS_SUMMARY WHERE TRIPS <= 0;
  INSERT INTO TRIP.TASK_RUN_LOG VALUES (CURRENT_TIMESTAMP(), :n_rows, :n_ins, :n_del, 'Applied stream delta');
  COMMIT;
  RETURN 'Applied ' || n_rows || ' change rows (' || n_ins || ' inserts, ' || n_del || ' deletes)';
END;
$$;

CREATE OR REPLACE TASK TRIP.TASK_REFRESH_TRIP_SUMMARY
  WAREHOUSE = BMTC_WH
  SCHEDULE = '60 MINUTE'
  COMMENT = 'Applies TRIP_DATA changes to TRIP_ANALYTICS_SUMMARY when the stream has data'
  WHEN SYSTEM$STREAM_HAS_DATA('BMTC_DW.TRIP.TRIP_DATA_STREAM')
AS
  CALL TRIP.SP_APPLY_TRIP_CHANGES();

ALTER TASK TRIP.TASK_REFRESH_TRIP_SUMMARY RESUME;
SHOW TASKS IN SCHEMA TRIP;

-- Reconciliation query (summary vs full recomputation) - should be 0
CREATE OR REPLACE VIEW TRIP.V_SUMMARY_RECONCILIATION AS
SELECT COUNT(*) AS MISMATCHED_ROUTE_DAYS FROM (
  SELECT ROUTE_ID, TRIP_DATE, COUNT(*) AS TRIPS, SUM(COALESCE(PASSENGER_COUNT, 0)) AS PASSENGERS,
         SUM(COALESCE(DELAY_MINUTES, 0)) AS TOTAL_DELAY_MIN
  FROM TRIP.TRIP_DATA GROUP BY ROUTE_ID, TRIP_DATE) f
FULL OUTER JOIN TRIP.TRIP_ANALYTICS_SUMMARY s ON s.ROUTE_ID = f.ROUTE_ID AND s.TRIP_DATE = f.TRIP_DATE
WHERE f.TRIPS IS DISTINCT FROM s.TRIPS OR f.PASSENGERS IS DISTINCT FROM s.PASSENGERS
   OR f.TOTAL_DELAY_MIN IS DISTINCT FROM s.TOTAL_DELAY_MIN;

SELECT * FROM TRIP.V_SUMMARY_RECONCILIATION;

-- ============================ End-to-end test ========================
-- Data change: two late-reported trips arrive, one trip delay is corrected
SELECT * FROM TRIP.TRIP_ANALYTICS_SUMMARY WHERE ROUTE_ID = 1 AND TRIP_DATE = '2026-10-31';
INSERT INTO TRIP.TRIP_DATA (TRIP_ID, BUS_ID, ROUTE_ID, DRIVER_ID, CONDUCTOR_ID, TRIP_DATE, SCHEDULED_START, ACTUAL_START,
                            ACTUAL_END, DELAY_MINUTES, PASSENGER_COUNT, DISTANCE_KM, TRIP_STATUS)
SELECT 900001, BUS_ID, ROUTE_ID, DRIVER_ID, CONDUCTOR_ID, '2026-10-31', '2026-10-31 21:00:00', '2026-10-31 21:04:00',
       '2026-10-31 21:50:00', 4, 0, DISTANCE_KM, 'COMPLETED' FROM TRIP.TRIP_DATA WHERE ROUTE_ID = 1 LIMIT 1;
INSERT INTO TRIP.TRIP_DATA (TRIP_ID, BUS_ID, ROUTE_ID, DRIVER_ID, CONDUCTOR_ID, TRIP_DATE, SCHEDULED_START, ACTUAL_START,
                            ACTUAL_END, DELAY_MINUTES, PASSENGER_COUNT, DISTANCE_KM, TRIP_STATUS)
SELECT 900002, BUS_ID, ROUTE_ID, DRIVER_ID, CONDUCTOR_ID, '2026-10-31', '2026-10-31 22:00:00', NULL, NULL, NULL, 0, 0,
       'CANCELLED' FROM TRIP.TRIP_DATA WHERE ROUTE_ID = 1 LIMIT 1;
SET corrected_trip = (SELECT MIN(TRIP_ID) FROM TRIP.TRIP_DATA WHERE TRIP_DATE = '2026-10-30' AND TRIP_STATUS = 'COMPLETED');
SET corrected_trip_delay = (SELECT DELAY_MINUTES FROM TRIP.TRIP_DATA WHERE TRIP_ID = $corrected_trip);
UPDATE TRIP.TRIP_DATA SET DELAY_MINUTES = DELAY_MINUTES + 20 WHERE TRIP_ID = $corrected_trip;

-- Stream detects the change
SELECT SYSTEM$STREAM_HAS_DATA('TRIP.TRIP_DATA_STREAM') AS STREAM_HAS_DATA;
SELECT TRIP_ID, ROUTE_ID, TRIP_DATE, TRIP_STATUS, DELAY_MINUTES, METADATA$ACTION, METADATA$ISUPDATE
FROM TRIP.TRIP_DATA_STREAM ORDER BY TRIP_ID, METADATA$ACTION;
SELECT * FROM TRIP.V_SUMMARY_RECONCILIATION;      -- summary is now stale (non-zero)

-- Task processes the change (manual trigger instead of waiting for the hourly schedule)
EXECUTE TASK TRIP.TASK_REFRESH_TRIP_SUMMARY;
SELECT SYSTEM$WAIT(40, 'SECONDS');
SELECT NAME, STATE, RETURN_VALUE, ERROR_MESSAGE, SCHEDULED_TIME, COMPLETED_TIME
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(TASK_NAME => 'TASK_REFRESH_TRIP_SUMMARY', RESULT_LIMIT => 5))
ORDER BY SCHEDULED_TIME DESC;
SELECT * FROM TRIP.TASK_RUN_LOG ORDER BY RUN_AT DESC;

-- Target updated
SELECT * FROM TRIP.TRIP_ANALYTICS_SUMMARY WHERE ROUTE_ID = 1 AND TRIP_DATE = '2026-10-31';
SELECT * FROM TRIP.V_SUMMARY_RECONCILIATION;      -- back to 0
SELECT SYSTEM$STREAM_HAS_DATA('TRIP.TRIP_DATA_STREAM') AS STREAM_HAS_DATA_AFTER_TASK;

-- Clean-up of the test change (also flows through stream + task, leaving source data unchanged)
DELETE FROM TRIP.TRIP_DATA WHERE TRIP_ID IN (900001, 900002);
UPDATE TRIP.TRIP_DATA SET DELAY_MINUTES = $corrected_trip_delay WHERE TRIP_ID = $corrected_trip;
EXECUTE TASK TRIP.TASK_REFRESH_TRIP_SUMMARY;
SELECT SYSTEM$WAIT(40, 'SECONDS');
SELECT * FROM TRIP.TASK_RUN_LOG ORDER BY RUN_AT DESC;
SELECT * FROM TRIP.V_SUMMARY_RECONCILIATION;
SELECT COUNT(*) AS TRIPS_NOW FROM TRIP.TRIP_DATA;
