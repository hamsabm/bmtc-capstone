-- ================================================================ Role tests
-- This account activates ALL secondary roles by default, which would let ACCOUNTADMIN
-- privileges leak into the tests. Disable them so each role is tested on its own.
USE SECONDARY ROLES NONE;
-- VIEWER: dashboards + secure views work, base tables are blocked
USE ROLE BMTC_VIEWER;
USE WAREHOUSE BMTC_WH;
SELECT TOTAL_BUSES, TOTAL_TRIPS, TOTAL_COMPLAINTS FROM BMTC_DW.TRIP.V_DASHBOARD_KPIS;
SELECT PASS_NUMBER, PASS_TYPE, STATUS, HAS_EMAIL_ON_FILE FROM BMTC_DW.PASSENGER.SV_PASS_HOLDERS LIMIT 3;
SELECT * FROM BMTC_DW.PASSENGER.PASS_DATA LIMIT 1;                      -- @expect_error (no table access)
SELECT * FROM BMTC_DW.TRIP.TICKET_DATA LIMIT 1;                         -- @expect_error (grant was revoked)
SELECT GET_DDL('VIEW', 'BMTC_DW.PASSENGER.SV_PASS_HOLDERS');            -- @expect_error (secure view definition hidden)

-- ANALYST: reads tables, PII masked, salary hidden, cannot write
USE ROLE BMTC_ANALYST;
SELECT PASSENGER_NAME, PHONE, EMAIL FROM BMTC_DW.PASSENGER.PASS_DATA WHERE EMAIL IS NOT NULL ORDER BY PASS_ID LIMIT 3;
SELECT EMPLOYEE_NAME, PHONE, MONTHLY_SALARY FROM BMTC_DW.BUS.EMPLOYEE_MASTER ORDER BY EMPLOYEE_ID LIMIT 3;
SELECT COUNT(DISTINCT DEPOT_ID) AS DEPOTS_VISIBLE_TO_ANALYST FROM BMTC_DW.BUS.EMPLOYEE_MASTER;
DELETE FROM BMTC_DW.TRIP.MAINTENANCE_LOG WHERE 1 = 0;                   -- @expect_error (read-only role)

-- MANAGER: contact details visible, salary hidden, only assigned depots visible
USE ROLE BMTC_MANAGER;
SELECT EMPLOYEE_NAME, PHONE, MONTHLY_SALARY FROM BMTC_DW.BUS.EMPLOYEE_MASTER ORDER BY EMPLOYEE_ID LIMIT 3;
SELECT DEPOT_ID, COUNT(*) AS EMPLOYEES_VISIBLE FROM BMTC_DW.BUS.EMPLOYEE_MASTER GROUP BY DEPOT_ID ORDER BY DEPOT_ID;
UPDATE BMTC_DW.TRIP.MAINTENANCE_LOG SET STATUS = STATUS WHERE 1 = 0;  -- allowed (no-op)
SELECT * FROM BMTC_DW.BUS.SV_DEPOT_PAYROLL_SUMMARY ORDER BY DEPOT_NAME, ROLE LIMIT 5;

-- ADMIN: everything
USE ROLE BMTC_ADMIN;
SELECT EMPLOYEE_NAME, PHONE, MONTHLY_SALARY FROM BMTC_DW.BUS.EMPLOYEE_MASTER ORDER BY EMPLOYEE_ID LIMIT 3;
SELECT COUNT(DISTINCT DEPOT_ID) AS DEPOTS_VISIBLE_TO_ADMIN FROM BMTC_DW.BUS.EMPLOYEE_MASTER;

