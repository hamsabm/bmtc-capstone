-- ---------------------------------------------------------------- Dynamic data masking
-- Re-runnable: detach policies before replacing them
ALTER TABLE PASSENGER.PASS_DATA MODIFY COLUMN PHONE UNSET MASKING POLICY;            -- @optional
ALTER TABLE PASSENGER.PASS_DATA MODIFY COLUMN EMAIL UNSET MASKING POLICY;            -- @optional
ALTER TABLE PASSENGER.PASS_DATA MODIFY COLUMN PASSENGER_NAME UNSET MASKING POLICY;   -- @optional
ALTER TABLE BUS.EMPLOYEE_MASTER MODIFY COLUMN PHONE UNSET MASKING POLICY;            -- @optional
ALTER TABLE BUS.EMPLOYEE_MASTER MODIFY COLUMN EMAIL UNSET MASKING POLICY;            -- @optional
ALTER TABLE BUS.EMPLOYEE_MASTER MODIFY COLUMN MONTHLY_SALARY UNSET MASKING POLICY;   -- @optional
ALTER TABLE BUS.EMPLOYEE_MASTER DROP ROW ACCESS POLICY GOVERNANCE.RAP_EMPLOYEE_DEPOT; -- @optional

CREATE OR REPLACE MASKING POLICY GOVERNANCE.MASK_PHONE AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BMTC_ADMIN', 'BMTC_MANAGER') THEN val
       WHEN val IS NULL THEN NULL
       ELSE 'XXXXXX' || RIGHT(val, 4) END;

CREATE OR REPLACE MASKING POLICY GOVERNANCE.MASK_EMAIL AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BMTC_ADMIN', 'BMTC_MANAGER') THEN val
       WHEN val IS NULL THEN NULL
       ELSE '*****@' || SPLIT_PART(val, '@', 2) END;

CREATE OR REPLACE MASKING POLICY GOVERNANCE.MASK_NAME AS (val VARCHAR) RETURNS VARCHAR ->
  CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BMTC_ADMIN', 'BMTC_MANAGER') THEN val
       WHEN val IS NULL THEN NULL
       ELSE LEFT(val, 1) || '*****' END;

-- Individual salaries: admins only. INVOKER_ROLE() is the view owner inside a view, so the
-- aggregate-only secure view SV_DEPOT_PAYROLL_SUMMARY can still total salaries for managers.
CREATE OR REPLACE MASKING POLICY GOVERNANCE.MASK_SALARY AS (val NUMBER(10,2)) RETURNS NUMBER(10,2) ->
  CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BMTC_ADMIN') THEN val
       WHEN INVOKER_ROLE() = 'ACCOUNTADMIN' AND CURRENT_ROLE() = 'BMTC_MANAGER' THEN val
       ELSE NULL END;

ALTER TABLE PASSENGER.PASS_DATA MODIFY COLUMN PHONE SET MASKING POLICY GOVERNANCE.MASK_PHONE;
ALTER TABLE PASSENGER.PASS_DATA MODIFY COLUMN EMAIL SET MASKING POLICY GOVERNANCE.MASK_EMAIL;
ALTER TABLE PASSENGER.PASS_DATA MODIFY COLUMN PASSENGER_NAME SET MASKING POLICY GOVERNANCE.MASK_NAME;
ALTER TABLE BUS.EMPLOYEE_MASTER MODIFY COLUMN PHONE SET MASKING POLICY GOVERNANCE.MASK_PHONE;
ALTER TABLE BUS.EMPLOYEE_MASTER MODIFY COLUMN EMAIL SET MASKING POLICY GOVERNANCE.MASK_EMAIL;
ALTER TABLE BUS.EMPLOYEE_MASTER MODIFY COLUMN MONTHLY_SALARY SET MASKING POLICY GOVERNANCE.MASK_SALARY;

-- ---------------------------------------------------------------- Row access policy (depot scoping)
CREATE OR REPLACE TABLE GOVERNANCE.DEPOT_ACCESS_MAP (ROLE_NAME VARCHAR, DEPOT_ID NUMBER)
COMMENT = 'Which role may see which depot rows; DEPOT_ID 0 = all depots';
INSERT INTO GOVERNANCE.DEPOT_ACCESS_MAP VALUES
  ('BMTC_MANAGER', 1), ('BMTC_MANAGER', 2),          -- demo zone manager: Shanthinagar + Yeshwanthpur
  ('BMTC_ANALYST', 0), ('BMTC_VIEWER', 0);

CREATE OR REPLACE ROW ACCESS POLICY GOVERNANCE.RAP_EMPLOYEE_DEPOT AS (depot NUMBER) RETURNS BOOLEAN ->
  CURRENT_ROLE() IN ('ACCOUNTADMIN', 'BMTC_ADMIN', 'SYSADMIN')
  OR EXISTS (SELECT 1 FROM GOVERNANCE.DEPOT_ACCESS_MAP m
             WHERE m.ROLE_NAME = CURRENT_ROLE() AND (m.DEPOT_ID = depot OR m.DEPOT_ID = 0));

ALTER TABLE BUS.EMPLOYEE_MASTER ADD ROW ACCESS POLICY GOVERNANCE.RAP_EMPLOYEE_DEPOT ON (DEPOT_ID);

