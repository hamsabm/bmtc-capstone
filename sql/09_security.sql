-- ---------------------------------------------------------------- Secure views (sensitive data hidden)
-- Pass holders without name/phone/e-mail; view definition hidden from consumers
CREATE OR REPLACE SECURE VIEW PASSENGER.SV_PASS_HOLDERS
COMMENT = 'Pass data without personal identifiers (secure view)' AS
SELECT PASS_ID, PASS_NUMBER, PASS_TYPE, PASSENGER_CATEGORY, ISSUE_DATE, VALID_FROM, VALID_TO, PRICE,
       ISSUING_DEPOT_ID, STATUS,
       IFF(EMAIL IS NULL, 'NO', 'YES') AS HAS_EMAIL_ON_FILE
FROM PASSENGER.PASS_DATA;

-- Staff directory without phone, e-mail or salary
CREATE OR REPLACE SECURE VIEW BUS.SV_EMPLOYEE_DIRECTORY
COMMENT = 'Workforce directory without contact details or salary (secure view)' AS
SELECT e.EMPLOYEE_CODE, e.EMPLOYEE_NAME, e.ROLE, d.DEPOT_NAME, e.JOIN_DATE, e.STATUS,
       DATEDIFF(YEAR, e.JOIN_DATE, '2026-10-31'::DATE) AS YEARS_OF_SERVICE
FROM BUS.EMPLOYEE_MASTER e JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = e.DEPOT_ID;

-- Workforce cost by depot: salary only in aggregate
CREATE OR REPLACE SECURE VIEW BUS.SV_DEPOT_PAYROLL_SUMMARY
COMMENT = 'Aggregated payroll per depot and role - no individual salaries' AS
SELECT d.DEPOT_NAME, e.ROLE, COUNT(*) AS HEADCOUNT, SUM(e.MONTHLY_SALARY) AS MONTHLY_PAYROLL
FROM BUS.EMPLOYEE_MASTER e JOIN BUS.DEPOT_MASTER d ON d.DEPOT_ID = e.DEPOT_ID
GROUP BY d.DEPOT_NAME, e.ROLE;

