-- 09_security.sql | Users, roles, privileges, role hierarchy (DCL),
-- secure views, dynamic data masking, row access policy + role tests.
--
-- Role hierarchy (privileges inherit upward):
--   BMTC_VIEWER -> BMTC_ANALYST -> BMTC_MANAGER -> BMTC_ADMIN -> SYSADMIN
--   VIEWER  : dashboards only (curated views + secure views), no base tables
--   ANALYST : read all project tables/views; PII masked; no writes
--   MANAGER : analyst + operational writes (maintenance, complaints, bus status),
--             sees contact details, row access limited to assigned depots
--   ADMIN   : full control of BMTC_DW objects + warehouse; sees all PII
-- ACCOUNTADMIN is not modified.
-- =====================================================================
