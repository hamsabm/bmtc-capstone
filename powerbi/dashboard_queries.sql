-- =====================================================================
-- powerbi/dashboard_queries.sql | BI semantic layer for Power BI
-- Creates two BI helper views, grants the BI role, then lists the KPI and
-- chart queries the dashboard is built from (all verified against BMTC_DW).
-- Run: venv\Scripts\python.exe scripts\run_sql.py powerbi\dashboard_queries.sql
-- =====================================================================
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE BMTC_WH;
USE DATABASE BMTC_DW;

-- Date dimension covering the data window (relate to every *_DATE column)
CREATE OR REPLACE VIEW TRIP.V_PBI_DIM_DATE COMMENT = 'Power BI date dimension' AS
SELECT d AS DATE_KEY, YEAR(d) AS YEAR, MONTH(d) AS MONTH_NO, MONTHNAME(d) AS MONTH_NAME,
       TO_CHAR(d, 'YYYY-MM') AS YEAR_MONTH, DAYOFWEEKISO(d) AS WEEKDAY_NO, DAYNAME(d) AS WEEKDAY,
       IFF(DAYOFWEEKISO(d) >= 6, 'Weekend', 'Weekday') AS DAY_TYPE, WEEKISO(d) AS ISO_WEEK
FROM (SELECT DATEADD(DAY, SEQ4(), '2025-11-01'::DATE) AS d FROM TABLE(GENERATOR(ROWCOUNT => 365)));

-- Route x day fact for revenue/ridership visuals (smaller than the 120k-row ticket table)
CREATE OR REPLACE VIEW TRIP.V_PBI_ROUTE_DAY_FACT COMMENT = 'Power BI fact: route x day' AS
SELECT t.TRIP_DATE AS DATE_KEY, t.ROUTE_ID, t.ROUTE_CODE, t.ROUTE_CATEGORY, t.DEPOT_NAME,
       COUNT(*) AS TRIPS, SUM(t.PASSENGER_COUNT) AS PASSENGERS, SUM(t.REVENUE) AS REVENUE,
       SUM(t.DISTANCE_KM) AS KM, SUM(t.DELAY_MINUTES) AS DELAY_MIN,
       COUNT_IF(t.DELAY_MINUTES <= 5) AS ON_TIME_TRIPS, COUNT_IF(t.TRIP_STATUS <> 'COMPLETED') AS FAILED_TRIPS,
       COUNT(t.DELAY_MINUTES) AS RUN_TRIPS   -- trips that actually ran (cancelled trips have no delay)
FROM TRIP.V_TRIP_DETAILS t
GROUP BY t.TRIP_DATE, t.ROUTE_ID, t.ROUTE_CODE, t.ROUTE_CATEGORY, t.DEPOT_NAME;

-- The BI service account role (BMTC_VIEWER) reads only curated views
GRANT SELECT ON VIEW TRIP.V_PBI_DIM_DATE TO ROLE BMTC_VIEWER;
GRANT SELECT ON VIEW TRIP.V_PBI_ROUTE_DAY_FACT TO ROLE BMTC_VIEWER;
GRANT SELECT ON VIEW TRIP.V_FUEL_EFFICIENCY_CLASSIFIED TO ROLE BMTC_VIEWER;
GRANT SELECT ON VIEW TRIP.V_MAINTENANCE_DETAILS TO ROLE BMTC_VIEWER;
GRANT SELECT ON VIEW BUS.V_BUS_SUMMARY TO ROLE BMTC_VIEWER;

-- ---------------------------------------------------------------- KPI cards
SELECT TOTAL_BUSES, TOTAL_ROUTES, TOTAL_TRIPS, TOTAL_TICKETS, TICKET_REVENUE, TOTAL_PASSES, ACTIVE_PASSES,
       TOTAL_COMPLAINTS, OPEN_COMPLAINTS, FUEL_COST, MAINTENANCE_COST, ON_TIME_PCT
FROM TRIP.V_DASHBOARD_KPIS;

-- ---------------------------------------------------------------- Trends (time analysis)
SELECT d.YEAR_MONTH, SUM(f.REVENUE) AS REVENUE, SUM(f.PASSENGERS) AS PASSENGERS, SUM(f.TRIPS) AS TRIPS
FROM TRIP.V_PBI_ROUTE_DAY_FACT f JOIN TRIP.V_PBI_DIM_DATE d ON d.DATE_KEY = f.DATE_KEY
GROUP BY d.YEAR_MONTH ORDER BY d.YEAR_MONTH;

SELECT d.WEEKDAY, d.WEEKDAY_NO, ROUND(AVG(x.PASSENGERS), 0) AS AVG_DAILY_PASSENGERS
FROM (SELECT DATE_KEY, SUM(PASSENGERS) AS PASSENGERS FROM TRIP.V_PBI_ROUTE_DAY_FACT GROUP BY DATE_KEY) x
JOIN TRIP.V_PBI_DIM_DATE d ON d.DATE_KEY = x.DATE_KEY
GROUP BY d.WEEKDAY, d.WEEKDAY_NO ORDER BY d.WEEKDAY_NO;

-- ---------------------------------------------------------------- Comparisons
SELECT DEPOT_NAME, SUM(REVENUE) AS REVENUE, SUM(PASSENGERS) AS PASSENGERS,
       ROUND(100 * SUM(ON_TIME_TRIPS) / SUM(RUN_TRIPS), 1) AS ON_TIME_PCT
FROM TRIP.V_PBI_ROUTE_DAY_FACT GROUP BY DEPOT_NAME ORDER BY REVENUE DESC;

SELECT BUS_TYPE, ROUND(AVG(KM_PER_UNIT), 2) AS AVG_KM_PER_UNIT, ROUND(AVG(COST_PER_KM), 2) AS AVG_COST_PER_KM
FROM TRIP.V_FUEL_EFFICIENCY_CLASSIFIED GROUP BY BUS_TYPE ORDER BY AVG_COST_PER_KM DESC;

-- ---------------------------------------------------------------- Category analysis
SELECT ROUTE_CATEGORY, SUM(REVENUE) AS REVENUE, SUM(PASSENGERS) AS PASSENGERS
FROM TRIP.V_PBI_ROUTE_DAY_FACT GROUP BY ROUTE_CATEGORY ORDER BY REVENUE DESC;

SELECT CATEGORY, PRIORITY, COUNT(*) AS COMPLAINTS FROM PASSENGER.V_COMPLAINT_ANALYTICS
GROUP BY CATEGORY, PRIORITY ORDER BY COMPLAINTS DESC;

SELECT MAINTENANCE_TYPE, COUNT(*) AS JOBS, SUM(TOTAL_COST) AS COST FROM TRIP.V_MAINTENANCE_DETAILS
GROUP BY MAINTENANCE_TYPE ORDER BY COST DESC;

-- ---------------------------------------------------------------- Top / bottom
SELECT ROUTE_CODE, ROUTE_CATEGORY, REVENUE, REVENUE_RANK FROM TRIP.V_ROUTE_PERFORMANCE
WHERE TRIPS > 0 QUALIFY REVENUE_RANK <= 10 OR REVENUE_RANK > COUNT(*) OVER () - 10 ORDER BY REVENUE_RANK;

SELECT REGISTRATION_NO, BUS_TYPE, DEPOT_NAME, MAINTENANCE_COST, KM_PER_UNIT FROM BUS.V_BUS_SUMMARY
ORDER BY MAINTENANCE_COST DESC LIMIT 10;

-- ---------------------------------------------------------------- Findings support (used in report findings)
SELECT PERIOD, ROUND(AVG(DELAY_MINUTES), 1) AS AVG_DELAY, ROUND(AVG(OCCUPANCY_RATIO), 2) AS AVG_OCCUPANCY
FROM TRIP.V_TRIP_DETAILS GROUP BY PERIOD;
